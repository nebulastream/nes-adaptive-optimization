


-- TWO WORKERS
-- 1) w1[SINK <- PROJECTION] <- w2[PREDICATE <- SOURCE]
-- 2) w1[SINK <- PREDICATE] <- w2[PROJECTION <- SOURCE]



CREATE WORKER 'worker-1:8080' SET (
       'worker-1:9090' AS DATA,
       1 AS CAPACITY
       );

CREATE WORKER 'worker-2:8080' SET (
       'worker-2:9090' AS DATA,
       'worker-1:8080' AS DOWNSTREAM,
       1 AS CAPACITY
       );

CREATE LOGICAL SOURCE source1(val1 UINT64 NOT NULL, val2 UINT64 NOT NULL);

CREATE PHYSICAL SOURCE FOR source1 TYPE Generator SET(
    'ALL' as "SOURCE".STOP_GENERATOR_WHEN_SEQUENCE_FINISHES,
    'CSV' as INPUT_FORMATTER."TYPE",
    'worker-2:8080' as "SOURCE"."HOST",
    3000000 as "SOURCE".MAX_RUNTIME_MS,
    'SEQUENCE UINT32 0 10000000 1, SEQUENCE UINT64 10000000 20000000 1' AS "SOURCE".GENERATOR_SCHEMA);


CREATE SINK someSink(result UINT64 NOT NULL) TYPE File SET(
       '/data/out.csv' as "SINK".FILE_PATH, 'CSV' as "SINK".OUTPUT_FORMAT,
       TRUE AS "OUTPUT_FORMATTER".ADD_EMITTED_TIME,
       'worker-1:8080' as "SINK"."HOST");

EXPLAIN SELECT VAL1 * 5 AS RESULT, VAL2
FROM source1
WHERE (VAL1 * VAL2) % 10 = 5
INTO someSink;
