CREATE WORKER 'worker-1:8080' SET ('worker-1:9090' AS DATA);
CREATE WORKER 'worker-2:8080' SET ('worker-2:9090' AS DATA, 'worker-1:8080' AS "DOWNSTREAM", 1 AS "CAPACITY");
CREATE WORKER 'worker-3:8080' SET ('worker-3:9090' AS DATA, 'worker-2:8080' AS "DOWNSTREAM", 1 AS "CAPACITY");

CREATE LOGICAL SOURCE endless(val1 UINT64 NOT NULL, val2 UINT64 NOT NULL, val3 UINT64 NOT NULL, ts UINT64 NOT NULL);

CREATE PHYSICAL SOURCE FOR endless TYPE Generator SET(
    'ALL' as "SOURCE".STOP_GENERATOR_WHEN_SEQUENCE_FINISHES,
    'CSV' as INPUT_FORMATTER."TYPE",
    'worker-2:8080' as "SOURCE"."HOST",
    3000000 as "SOURCE".MAX_RUNTIME_MS,
    'SEQUENCE UINT32 0 10000000 1, SEQUENCE UINT64 0 10000000 1, SEQUENCE UINT32 0 10000000 1, SEQUENCE UINT64 0 10000000 1' AS "SOURCE".GENERATOR_SCHEMA);

CREATE SINK someSink(r1 UINT64 NOT NULL, r2 UINT64 NOT NULL, ts UINT64 NOT NULL) TYPE File SET(
       '/data/out.csv' as "SINK".FILE_PATH, 'CSV' as "SINK".OUTPUT_FORMAT,
       TRUE AS "OUTPUT_FORMATTER".ADD_EMITTED_TIME,
       'worker-1:8080' as "SINK"."HOST",
       false AS "SINK"."APPEND");

SELECT val3 AS r1, val * 2 AS r2, ts
FROM (
    SELECT val1 + val2 AS val, val3, ts
    FROM endless
)
WHERE val % 5 > 0
INTO someSink;
